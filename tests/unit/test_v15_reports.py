def test_pre_outcome_lock_refresh_rejects_opened_outcomes(tmp_path: Path) -> None:
    from experiments.v15.configuration import build_lock, refresh_pre_outcome_lock

    config = tmp_path / "configs/v15"
    config.mkdir(parents=True)
    for source, name in ((Path("configs/v15/confirmatory.yaml"), "confirmatory.yaml"), (Path("configs/v15/task_manifest.json"), "task_manifest.json"), (Path("configs/v15/external_versions.json"), "external_versions.json")):
        (config / name).write_bytes(source.read_bytes())
    lock_path = tmp_path / "experiments/v15/confirmatory_lock.json"
    lock_path.parent.mkdir(parents=True)
    lock = build_lock(tmp_path)
    lock["confirmatory_execution"] = "COMPLETED"
    unsigned = dict(lock)
    unsigned.pop("lock_hash")
    import hashlib

    from experiments.v15.protocol import canonical_json
    lock["lock_hash"] = hashlib.sha256(canonical_json(unsigned).encode()).hexdigest()
    lock_path.write_text(__import__("json").dumps(lock, indent=2, sort_keys=True) + "\n", encoding="utf-8")

    with pytest.raises(PermissionError, match="outcomes"):
        refresh_pre_outcome_lock(tmp_path, lock_path)


def test_confirmatory_lock_opening_is_hashed_and_idempotent(tmp_path: Path) -> None:
    import json

    from experiments.v15.configuration import (
        _lock_digest,
        build_lock,
        is_confirmatory_open,
        open_confirmatory_lock,
    )

    config = tmp_path / "configs/v15"
    config.mkdir(parents=True)
    for source, name in (
        (Path("configs/v15/confirmatory.yaml"), "confirmatory.yaml"),
        (Path("configs/v15/task_manifest.json"), "task_manifest.json"),
        (Path("configs/v15/external_versions.json"), "external_versions.json"),
    ):
        (config / name).write_bytes(source.read_bytes())
    lock_path = tmp_path / "experiments/v15/confirmatory_lock.json"
    lock_path.parent.mkdir(parents=True)
    lock_path.write_text(json.dumps(build_lock(tmp_path), sort_keys=True), encoding="utf-8")

    open_confirmatory_lock(tmp_path, lock_path, phase="transition_audit")
    opened = json.loads(lock_path.read_text(encoding="utf-8"))
    assert is_confirmatory_open(opened["confirmatory_execution"])
    assert opened["confirmatory_execution"]["status"] == "OPENED"
    assert opened["confirmatory_execution"]["phase"] == "transition_audit"
    assert opened["lock_hash"] == _lock_digest(opened)
    before = lock_path.read_bytes()

    open_confirmatory_lock(tmp_path, lock_path, phase="promotion_replay")

    assert lock_path.read_bytes() == before
