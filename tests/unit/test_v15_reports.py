def test_confirmatory_lock_is_not_overwritten_by_report_generation(tmp_path: Path) -> None:
    from experiments.v15.configuration import build_lock, ensure_lock

    config = tmp_path / "configs/v15"
    config.mkdir(parents=True)
    source_config = Path("configs/v15/confirmatory.yaml")
    source_tasks = Path("configs/v15/task_manifest.json")
    source_external = Path("configs/v15/external_versions.json")
    for source, name in ((source_config, "confirmatory.yaml"), (source_tasks, "task_manifest.json"), (source_external, "external_versions.json")):
        (config / name).write_bytes(source.read_bytes())

    lock_path = tmp_path / "experiments/v15/confirmatory_lock.json"
    lock_path.parent.mkdir(parents=True)
    original = build_lock(tmp_path)
    lock_path.write_text(__import__("json").dumps(original, indent=2, sort_keys=True) + "\n", encoding="utf-8")
    before = lock_path.read_bytes()

    ensured = ensure_lock(tmp_path, lock_path)

    assert ensured == lock_path
    assert lock_path.read_bytes() == before


