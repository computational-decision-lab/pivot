from __future__ import annotations

import json
from collections.abc import Mapping
from pathlib import Path
from typing import Any

from .audit_support import cli, write_audit
from .configuration import is_confirmatory_open
from .figure_pipeline import _load_visual_review
from .protocol import file_hash

REQUIRED = (
    "configs/v15/confirmatory.yaml",
    "configs/v15/task_manifest.json",
    "configs/v15/external_versions.json",
    "experiments/v15/confirmatory_lock.json",
    "results/v15/canonical/manifest.json",
    "results/v15/dev-smoke/manifest.json",
    "results/v15/candidate-archive/manifest.json",
    "results/v15/promotion-replay/manifest.json",
    "artifacts/v15/figure_status.json",
    "figures/v15/visual_review_manifest.json",
    "artifacts/v15/scientific_summary.json",
    "artifacts/v15/terminal_state_audit.json",
    "V15_SCIENTIFIC_SUMMARY.md",
    "snapshot/v15_pre_modern_agent/PROVENANCE.txt",
)

_REQUIRED_DEV_PHASES = frozenset(
    {
        "dev-external-transition-audit",
        "dev-external-promotion",
        "dev-external-closed-loop",
        "dev-pi-replication",
        "dev-external-ablations",
    }
)


def external_execution_status(
    phase_statuses: Mapping[str, str], *, confirmatory_open: bool
) -> str:
    """Describe the strongest externally verified runtime state."""

    if confirmatory_open:
        return "CONFIRMATORY_EXECUTION_OPENED"
    required_ok = all(phase_statuses.get(name) == "COMPLETED" for name in _REQUIRED_DEV_PHASES)
    strategic_ok = phase_statuses.get("dev-external-strategic-response") in {"COMPLETED", "PARTIAL"}
    if required_ok and strategic_ok:
        return "PINNED_DEV_RUNTIME_VERIFIED; CONFIRMATORY_NOT_OPENED"
    return "NOT_RUN: pinned DEV runtime artifacts incomplete"


def audit_reproducibility(root: Path) -> dict[str, Any]:
    root = Path(root).resolve()
    present = {relative: (root / relative).is_file() for relative in REQUIRED}
    phase_statuses: dict[str, str] = {}
    for phase in (
        "dev-external-transition-audit",
        "dev-external-promotion",
        "dev-external-closed-loop",
        "dev-pi-replication",
        "dev-external-strategic-response",
        "dev-external-ablations",
    ):
        manifest = root / "results/v15" / phase / "manifest.json"
        if manifest.is_file():
            try:
                payload = json.loads(manifest.read_text(encoding="utf-8"))
                phase_statuses[phase] = str(payload.get("status", "")) if isinstance(payload, Mapping) else ""
            except (OSError, json.JSONDecodeError):
                phase_statuses[phase] = ""
    lock_path = root / "experiments/v15/confirmatory_lock.json"
    confirmatory_open = False
    if lock_path.is_file():
        try:
            lock = json.loads(lock_path.read_text(encoding="utf-8"))
            confirmatory_open = isinstance(lock, Mapping) and is_confirmatory_open(
                lock.get("confirmatory_execution")
            )
        except (OSError, json.JSONDecodeError):
            confirmatory_open = False
    terminal_path = root / "artifacts/v15/terminal_state_audit.json"
    terminal_payload: Mapping[str, Any] | None = None
    if terminal_path.is_file():
        try:
            loaded_terminal = json.loads(terminal_path.read_text(encoding="utf-8"))
            if isinstance(loaded_terminal, Mapping):
                terminal_payload = loaded_terminal
        except (OSError, json.JSONDecodeError):
            terminal_payload = None
    terminal_valid = bool(terminal_payload and terminal_payload.get("valid", False))
    reviewed_figures, visual_review_error = _load_visual_review(root)
    visual_review_valid = visual_review_error is None and bool(reviewed_figures)
    # The artifact is generated by the same command as the other reports; a
    # missing or blocked closure audit is a reproducibility blocker even when
    # the source files happen to be present.
    result = {
        "required_artifacts": present,
        "missing": [relative for relative, exists in present.items() if not exists],
        "dev_only_artifacts_explicit": True,
        "external_execution_status": external_execution_status(
            phase_statuses, confirmatory_open=confirmatory_open
        ),
        "external_phase_statuses": phase_statuses,
        "terminal_state_audit": {
            "present": terminal_path.is_file(),
            "valid": terminal_valid,
            "sha256": file_hash(terminal_path) if terminal_path.is_file() else None,
        },
        "visual_review": {
            "valid": visual_review_valid,
            "figure_count": len(reviewed_figures),
            "error": visual_review_error,
        },
        "valid": all(present.values()) and terminal_valid and visual_review_valid,
    }
    return write_audit(
        root,
        "reproducibility_audit",
        result,
        "Reproducibility Audit",
        "Protocol inputs, lock, canonical schemas, candidate provenance, figure passports, and the preserved baseline are checked for presence.",
    )


if __name__ == "__main__":
    cli(audit_reproducibility, "Audit reproducibility artifacts")
